/** Lifted off the ground so the road wins the depth fight with it. */
export const ROAD_LIFT = 0.06;

/** Footway either side of a carriageway. Fits inside SLOT.setback, so no building has to move. */
export const SIDEWALK_WIDTH = 2.6;
/** Kerb height. Enough to read as a step, low enough that nothing has to climb it. */
export const SIDEWALK_LIFT = ROAD_LIFT + 0.18;

/** A highway's guardrail, standing where a sidewalk would otherwise go. */
const GUARDRAIL_HEIGHT = 0.85;

/** Zebra stripes: painted on the carriageway just outside the junction each arm runs into. */
const STRIPE_WIDTH = 0.9;
const MARK_LIFT = ROAD_LIFT + 0.05;

/** Every possible lane-to-lane movement through an ordinary junction, in the Traffic view. */
const turnColor = new Color3(0.75, 0.5, 0.95);
/** Same idea, for every possible crossing a pedestrian could make between two arms' sidewalks. */
const walkTurnColor = new Color3(0.55, 0.85, 0.55);

/**
 * Turns the graph into road surface. Every mesh here is derived: `rebuild` disposes what
 * it made and builds again from the graph, and nothing else ever touches these meshes.
 */
export function createRoadRenderer(scene: Scene, graph: RoadGraph) {
  const material = new StandardMaterial("road", scene);
  material.diffuseColor = new Color3(0.18, 0.18, 0.19);
  // A footpath in the same asphalt as a street reads as a street. Paving reads as somewhere to walk.
  const pavingMaterial = new StandardMaterial("paving", scene);
  pavingMaterial.diffuseColor = new Color3(0.56, 0.53, 0.48);
  pavingMaterial.specularColor = Color3.Black();
  // Footway strips are generated by several builders -- straight runs, junction corners, arcs
  // around a ring -- and their winding depends on which way each one walks its points. They are
  // all flat and seen from above, so drawing both faces is cheaper than getting every winding
  // right. ponytail: one flag, not four orientation arguments.
  pavingMaterial.backFaceCulling = false;
  const paintMaterial = new StandardMaterial("road_paint", scene);
  paintMaterial.diffuseColor = new Color3(0.88, 0.88, 0.85);
  paintMaterial.specularColor = Color3.Black();
  material.specularColor = Color3.Black();
  const portalMaterial = new StandardMaterial("tunnel_portal", scene);
  portalMaterial.diffuseColor = new Color3(0.26, 0.25, 0.23);
  portalMaterial.specularColor = Color3.Black();
  const tubeMaterial = new StandardMaterial("tunnel_tube", scene);
  tubeMaterial.diffuseColor = new Color3(0.06, 0.06, 0.055);
  tubeMaterial.emissiveColor = new Color3(0.01, 0.008, 0.006);
  tubeMaterial.specularColor = Color3.Black();
  const curb = new Color3(0.52, 0.55, 0.53);
  const lane = new Color3(0.86, 0.78, 0.48);
  const tunnel = new Color3(0.58, 0.55, 0.49);
  // The Traffic view's own lane overlay: one colour per direction of travel, so how many lanes a
  // road has and which way each one flows both read at a glance.
  const laneOutbound = new Color3(0.3, 0.85, 0.95);
  const laneInbound = new Color3(0.95, 0.45, 0.25);
  // A distinct pair for foot traffic, so a sidewalk's lane doesn't read as one more car lane.
  const walkOutbound = new Color3(0.55, 0.9, 0.4);
  const walkInbound = new Color3(0.95, 0.85, 0.35);
  const guardrailMaterial = new StandardMaterial("guardrail", scene);
  guardrailMaterial.emissiveColor = new Color3(0.62, 0.64, 0.65);
  guardrailMaterial.specularColor = Color3.Black();
  guardrailMaterial.disableLighting = true;
  guardrailMaterial.backFaceCulling = false;

  let meshes: (Mesh | LinesMesh)[] = [];
  let faded = false;

  /**
   * The Traffic view's own use for this: the lane overlay is the thing to read, so the road
   * surface and everything painted on it fade back rather than competing with it -- except the
   * overlay's own lines, which are the one thing this view exists to make MORE visible, not less.
   * The solid meshes (asphalt, paving, paint, guardrail) share one material each, so setting it
   * once reaches every mesh built from it; a `LinesMesh` (kerbs, dividers) has no material to
   * share, so each one already in `meshes` gets its own alpha directly.
   */
  function applyFade(): void {
    const alpha = faded ? 0.35 : 1;
    for (const m of [material, pavingMaterial, paintMaterial, guardrailMaterial]) {
      m.alpha = alpha;
      m.transparencyMode = alpha < 1 ? Material.MATERIAL_ALPHABLEND : Material.MATERIAL_OPAQUE;
    }
    for (const mesh of meshes) {
      if (mesh.name.startsWith("traffic_lane_") || mesh.name.startsWith("traffic_walk_")) continue;
      if ("alpha" in mesh) (mesh as LinesMesh).alpha = alpha;
    }
  }
  let showTraffic = false;

  function rebuild(dirty?: TerrainBounds): void {
    if (dirty) {
      const segmentsById = new Map(graph.allSegments().map((segment) => [segment.id, segment]));
      meshes = meshes.filter((mesh) => {
        if (!meshTouchesDirty(segmentsById, mesh, dirty)) return true;
        mesh.dispose();
        return false;
      });
    } else {
      for (const mesh of meshes) mesh.dispose();
      meshes = [];
    }

    const junctions = allJunctions(graph);

    for (const seg of graph.allSegments()) {
      const type = roadType(seg.type);
      if (dirty && !segmentMeshTouchesBounds(seg.samples, type, dirty)) continue;
      if (type.tunnelDepth) {
        const steps = Math.max(4, Math.ceil(seg.length / 8));
        const trace = pointsBetween(graph, seg.id, 0, seg.length, steps, MARK_LIFT);
        const line = MeshBuilder.CreateDashedLines(`tunnel_trace_${seg.id}`, { points: trace, dashSize: 8, gapSize: 5 }, scene);
        line.color = tunnel;
        line.isPickable = false;

        const tube = tunnelMesh(scene, `tunnel_${seg.id}`, graph, seg.id, steps, type.width);
        tube.shell.material = portalMaterial;
        tube.interior.material = tubeMaterial;
        tube.shell.isPickable = false;
        tube.interior.isPickable = false;
        meshes.push(line, tube.shell, tube.interior);
        meshes.push(...tunnelPortals(scene, graph, seg.id, type.width, portalMaterial, tunnel));
        continue;
      }

      const half = type.width / 2;
      const isAvenue = baseRoadTypeId(seg.type) === "avenue";
      // The surface stops short of each junction; the junction polygon closes the gap.
      const { start, end } = segmentTrims(junctions, graph, seg.id);
      const from = start;
      const to = seg.length - end;
      if (to - from < 0.25) continue; // wholly inside its junctions

      const left: Vector3[] = [];
      const right: Vector3[] = [];
      const steps = Math.max(2, Math.ceil((to - from) / 2));
      for (let i = 0; i <= steps; i++) {
        const d = from + ((to - from) * i) / steps;
        const { position, tangent } = graph.pointAt(seg.id, d);
        const n = perpXZ(normalizeXZ(tangent));
        left.push(new Vector3(position.x + n.x * half, position.y + ROAD_LIFT, position.z + n.z * half));
        right.push(new Vector3(position.x - n.x * half, position.y + ROAD_LIFT, position.z - n.z * half));
      }

      const ribbon = roadStripMesh(scene, `road_${seg.id}`, left, right);
      ribbon.material = type.pedestrian ? pavingMaterial : material;
      ribbon.isPickable = false;
      meshes.push(ribbon);
      meshes.push(styledLine(scene, `curb_l_${seg.id}`, left, curb), styledLine(scene, `curb_r_${seg.id}`, right, curb));

      // A footway either side, stepped up from the carriageway. A path is already all footway.
      // A highway gets no frontage to walk to, so it gets a guardrail in place of the sidewalk.
      if (type.highway) {
        const topLeft = left.map((p) => p.add(new Vector3(0, GUARDRAIL_HEIGHT, 0)));
        const topRight = right.map((p) => p.add(new Vector3(0, GUARDRAIL_HEIGHT, 0)));
        const railLeft = roadStripMesh(scene, `guardrail_l_${seg.id}`, left, topLeft);
        const railRight = roadStripMesh(scene, `guardrail_r_${seg.id}`, right, topRight);
        for (const rail of [railLeft, railRight]) {
          rail.material = guardrailMaterial;
          rail.isPickable = false;
          meshes.push(rail);
        }
      } else if (!type.pedestrian) {
        const outerLeft: Vector3[] = [];
        const outerRight: Vector3[] = [];
        const innerLeft: Vector3[] = [];
        const innerRight: Vector3[] = [];
        for (let i = 0; i <= steps; i++) {
          const d = from + ((to - from) * i) / steps;
          const { position, tangent } = graph.pointAt(seg.id, d);
          const n = perpXZ(normalizeXZ(tangent));
          const y = position.y + SIDEWALK_LIFT;
          const out = half + SIDEWALK_WIDTH;
          innerLeft.push(new Vector3(position.x + n.x * half, y, position.z + n.z * half));
          outerLeft.push(new Vector3(position.x + n.x * out, y, position.z + n.z * out));
          innerRight.push(new Vector3(position.x - n.x * half, y, position.z - n.z * half));
          outerRight.push(new Vector3(position.x - n.x * out, y, position.z - n.z * out));
        }
        const walkLeft = roadStripMesh(scene, `sidewalk_l_${seg.id}`, outerLeft, innerLeft);
        const walkRight = roadStripMesh(scene, `sidewalk_r_${seg.id}`, innerRight, outerRight);
        for (const walk of [walkLeft, walkRight]) {
          walk.material = pavingMaterial;
          walk.isPickable = false;
          meshes.push(walk);
        }
      }
      // A two-way avenue always gets a centre line (it is wide enough to read as two directions);
      // a 2-lane two-way road gets the same line as its lane divider. One-way never draws one --
      // there is no opposing direction to keep apart, so no lane count on a one-way road needs it.
      if (!type.oneWay && (isAvenue || type.lanes === 2)) {
        const center = pointsBetween(graph, seg.id, from, to, steps, MARK_LIFT);
        meshes.push(styledLine(scene, `lane_${seg.id}`, center, lane));
      }

      // The Traffic view: every physical lane drawn at the same offset a car in it actually
      // uses, coloured by which direction it carries. An ordinary junction gets its own proper
      // turn diagram (below, `junctionTurnLines`), so a lane line only has to reach its own trim.
      if (showTraffic && !type.pedestrian) {
        for (const [i, laneCentre] of laneCentres(type).entries()) {
          const points = pointsBetween(graph, seg.id, from, to, steps, MARK_LIFT + 0.02, laneCentre.offset);
          meshes.push(styledLine(scene, `traffic_lane_${seg.id}_${i}`, points, laneCentre.direction === 1 ? laneOutbound : laneInbound));
        }
        // Where traffic crosses between the lanes it has: the middle third of the road, one
        // weave per direction, drawn along the very path a car changing lane travels.
        meshes.push(...laneChangeLines(scene, graph, seg, type, from, to, turnColor));
      }
      // Same idea for foot traffic: a path's own lane, or an ordinary road's sidewalks either
      // side. A highway has no footway at all to draw one on. A path is paved at the carriageway's
      // own height, but an ordinary road's sidewalk is a stepped-up mesh of its own -- the line has
      // to clear that step too, or the sidewalk itself draws over it. An ordinary junction gets its
      // own crossing diagram too (below), so a sidewalk line only has to reach its own trim.
      if (showTraffic && !type.highway) {
        const walkLift = type.pedestrian ? MARK_LIFT + 0.02 : SIDEWALK_LIFT + 0.03;
        for (const [i, walkCentre] of walkCentres(type, SIDEWALK_WIDTH).entries()) {
          const points = pointsBetween(graph, seg.id, from, to, steps, walkLift, walkCentre.offset);
          meshes.push(styledLine(scene, `traffic_walk_${seg.id}_${i}`, points, walkCentre.direction === 1 ? walkOutbound : walkInbound));
        }
      }
    }

    // A crossing wherever someone on foot has to walk over a carriageway to get where the
    // footways go -- read off those transfers themselves, so the paint marks a real movement
    // rather than every arm on principle. A highway carries no footway, so nothing crosses it.
    for (const junction of junctions.values()) {
      if (dirty && !junctionTouchesBounds(junction, dirty)) continue;
      const paths = walkCrossings(graph, junction, junctions);
      for (const arm of junction.arms) {
        const type = roadType(graph.segment(arm.segment).type);
        if (type.tunnelDepth || type.pedestrian) continue;
        const reach = arm.trim + CROSSING_GAP + CROSSING_DEPTH * 2;
        if (!crossesRoad(graph.node(junction.node).pos, arm.outward, reach, paths)) continue;
        // How much road there is between this junction and whatever is at the other end.
        const room = roomOn(graph, junctions, arm, junction.node);
        meshes.push(...crossingMeshes(scene, graph, junction.node, arm, type.width, paintMaterial, room));
      }
    }

    for (const junction of junctions.values()) {
      if (dirty && !junctionTouchesBounds(junction, dirty)) continue;
      if (junction.roundabout > 0) {
        meshes.push(...roundaboutMeshes(scene, graph, junction, material, curb, pavingMaterial, lane));
        // The Traffic view's own lane overlay: a roundabout is always one direction, so every
        // lane on it reads as "outbound" -- there is no opposing lane to contrast it against.
        if (showTraffic) {
          const centre = graph.node(junction.node).pos;
          const elevationAt = ringElevation(junction.arms, centre.y);
          const radii = ringLaneRadii(graph, junction.node, junction.roundabout);
          for (const [i, radius] of radii.entries()) {
            const points = Array.from({ length: 65 }, (_, s) => {
              const angle = (s / 64) * Math.PI * 2;
              const y = elevationAt(angle) + MARK_LIFT + 0.02;
              return new Vector3(centre.x + Math.cos(angle) * radius, y, centre.z + Math.sin(angle) * radius);
            });
            meshes.push(styledLine(scene, `traffic_lane_roundabout_${junction.node}_${i}`, points, laneOutbound));
          }
          // How a car actually gets between an arm's lanes and that ring, drawn like the turn
          // diagram an ordinary junction gets.
          meshes.push(...roundaboutTurnLines(scene, graph, junction, radii, turnColor));
          // And the same for people on foot: the footway circles the ring outside the kerb, and
          // each arm's two walkways join it.
          for (const [i, path] of walkTransferPaths(graph, junction, junctions).entries()) {
            meshes.push(styledLine(scene, `traffic_walk_turn_${junction.node}_${i}`, lift(path, SIDEWALK_LIFT + 0.03), walkTurnColor));
          }
        }
        continue;
      }
      const mesh = junctionMesh(scene, junction);
      if (!mesh) continue;
      mesh.material = material;
      mesh.isPickable = false;
      meshes.push(mesh);
      // The footways have to close around the junction too, or every sidewalk stops dead at it.
      meshes.push(...junctionFootway(scene, graph, junction, pavingMaterial));

      if (showTraffic) {
        meshes.push(...junctionTurnLines(scene, graph, junction, turnColor));
        for (const [i, path] of walkTransferPaths(graph, junction, junctions).entries()) {
          meshes.push(styledLine(scene, `traffic_walk_turn_${junction.node}_${i}`, lift(path, SIDEWALK_LIFT + 0.03), walkTurnColor));
        }
      }
    }

    applyFade();
  }

  return {
    rebuild,
    material,
    setShowTraffic(next: boolean) {
      if (showTraffic === next) return;
      showTraffic = next;
      rebuild();
    },
    setFaded(next: boolean) {
      faded = next;
      applyFade();
    },
  };
}

/**
 * The ring itself: a flat annulus from the kerb of the island out to where the arms were trimmed.
 * Carriageway width is the widest road meeting the node, which is the same reference the radius
 * takes. ponytail: a lathe over two points, not a swept road built from the graph.
 */
/**
 * One zebra across an arm, laid just beyond where the junction surface ends. Stripes run along
 * the road, so they read as a crossing rather than as lane markings.
 * ponytail: a strip mesh per stripe, reusing the ribbon builder the roads already use.
 */
function crossingMeshes(
  scene: Scene,
  graph: RoadGraph,
  nodeId: NodeId,
  arm: JunctionArm,
  width: number,
  paint: StandardMaterial,
  room: number,
): Mesh[] {
  const seg = graph.segment(arm.segment);
  const atStart = seg.a === nodeId;
  // Sits just clear of the junction, and gives up that clearance before it gives up the crossing
  // itself: a roundabout holds its arms back by a whole ring radius, so a road between two of
  // them has far less room than its length suggests -- and people cross it all the same.
  const near = crossingNear(arm, room);
  const far = near + CROSSING_DEPTH;
  if (room < CROSSING_DEPTH) return [];

  const half = width / 2;
  const stripes = Math.max(2, Math.floor(width / (STRIPE_WIDTH * 2)));
  const pitch = width / stripes;
  const out: Mesh[] = [];

  // Both rows run the way the segment does, and the two sides keep the road ribbon's own order
  // of left and right. Laid from the junction outwards instead, a crossing at the near end of a
  // road came out wound the other way up and was culled away: whether one showed at all came
  // down to which direction that road happened to have been drawn in.
  const rows = [near, far].map((d) => (atStart ? d : seg.length - d)).sort((l, r) => l - r);

  for (let i = 0; i < stripes; i++) {
    const centre = -half + pitch * (i + 0.5);
    const left: Vector3[] = [];
    const right: Vector3[] = [];
    for (const along of rows) {
      const { position, tangent } = graph.pointAt(arm.segment, along);
      const n = perpXZ(normalizeXZ(tangent));
      const lo = centre - STRIPE_WIDTH / 2;
      const hi = centre + STRIPE_WIDTH / 2;
      const y = position.y + MARK_LIFT;
      left.push(new Vector3(position.x + n.x * hi, y, position.z + n.z * hi));
      right.push(new Vector3(position.x + n.x * lo, y, position.z + n.z * lo));
    }
    const stripe = roadStripMesh(scene, `crossing_${arm.segment}_${nodeId}_${i}`, left, right);
    stripe.material = paint;
    stripe.isPickable = false;
    out.push(stripe);
  }
  return out;
}

function roundaboutMeshes(
  scene: Scene,
  graph: RoadGraph,
  junction: JunctionGeometry,
  surface: StandardMaterial,
  kerb: Color3,
  paving: StandardMaterial,
  laneColor: Color3,
): Mesh[] {
  const centre = graph.node(junction.node).pos;
  const outer = junction.roundabout;
  const reference = widestIncidentRoad(graph, junction.node);
  const lane = Math.max(6, reference?.width ?? 0);
  const inner = Math.max(3, outer - lane);
  // A ring between footpaths is paved, like the paths themselves.
  const onFoot = reference?.pedestrian === true;

  // A flat ring at one elevation only agrees with every road meeting it if the ground is flat
  // too -- on a slope, an arm arrives at its own elevation, not the node's, and a flat ring can
  // come out above or below it, showing as a gap right at the seam. Reading the ring's height
  // off the same per-arm elevations the arms' own corners already carry, blended smoothly
  // between one arm and the next, means the ring always meets every road exactly where it is.
  const elevationAt = ringElevation(junction.arms, centre.y);

  const ringPoints = (radius: number): Vector3[] =>
    Array.from({ length: 41 }, (_, i) => {
      const angle = (i / 40) * Math.PI * 2;
      // A little more clearance than an ordinary road: the ring's disc is much wider than any
      // single road is, so it has more terrain to clear underneath it, and a couple of
      // centimetres extra here is cheap insurance against whatever the flatten still leaves
      // imperfect.
      const y = elevationAt(angle) + ROAD_LIFT + 0.15;
      return new Vector3(centre.x + Math.cos(angle) * radius, y, centre.z + Math.sin(angle) * radius);
    });
  const ring = roadStripMesh(scene, `roundabout_${junction.node}`, ringPoints(inner), ringPoints(outer));
  ring.material = onFoot ? paving : surface;
  ring.isPickable = false;

  const circle = (radius: number): Vector3[] =>
    Array.from({ length: 41 }, (_, i) => {
      const angle = (i / 40) * Math.PI * 2;
      return new Vector3(centre.x + Math.cos(angle) * radius, elevationAt(angle) + MARK_LIFT, centre.z + Math.sin(angle) * radius);
    });

  const lanes = graph.node(junction.node).roundaboutLanes;

  return [
    ring,
    // A footway ring outside it, but broken where the arms come in: a full lathe would lay a band
    // straight across every road meeting the roundabout. A path is all footway already.
    ...(onFoot ? [] : footwayArcs(scene, graph, junction, centre, outer, elevationAt, paving)),
    styledLine(scene, `roundabout_kerb_out_${junction.node}`, circle(outer), kerb),
    styledLine(scene, `roundabout_kerb_in_${junction.node}`, circle(inner), kerb),
    // A second lane's own divider, the same colour as a straight road's centre line.
    ...(lanes === 2 && !onFoot ? [styledLine(scene, `roundabout_lane_${junction.node}`, circle((inner + outer) / 2), laneColor)] : []),
  ];
}


/**
 * Closes the footway around an ordinary junction. The junction polygon already has exactly the
 * right outline: each edge is either the mouth of a road, or a stretch of kerb between two roads.
 * Sweeping every non-mouth edge outwards gives the corner paving, and cannot cut across the
 * junction the way joining arm corners pairwise could.
 * ponytail: walk the hull that is already computed, rather than deriving a second polygon.
 */
function junctionFootway(
  scene: Scene,
  graph: RoadGraph,
  junction: JunctionGeometry,
  paving: StandardMaterial,
): Mesh[] {
  const ring = junction.ring;
  if (ring.length < 3) return [];

  const centroid = ring.reduce((sum, p) => ({ x: sum.x + p.x / ring.length, z: sum.z + p.z / ring.length }), {
    x: 0,
    z: 0,
  });
  // Two neighbouring arms each compute their shared corner independently, from their own
  // (possibly curved) centreline -- they land within a few centimetres of each other, not
  // exactly on top. A tighter epsilon here misses that match, misreads the mouth as a kerb
  // gap, and pastes a sidewalk patch straight onto the carriageway.
  const same = (a: Vec3, b: Vec3): boolean => Math.hypot(a.x - b.x, a.z - b.z) < 0.15;
  /** True when this edge is where a road opens onto the junction, which must stay clear. */
  const isMouth = (a: Vec3, b: Vec3): boolean =>
    junction.arms.some(
      (arm) =>
        (same(a, arm.cornerLow) && same(b, arm.cornerHigh)) || (same(a, arm.cornerHigh) && same(b, arm.cornerLow)),
    );

  // A narrower road can meet this node without ever reaching the hull -- its corners sit
  // inside the ring, pulled behind the wider roads either side of it. The kerb edge that
  // "closes" the gap those wide roads leave then actually runs straight over that narrower
  // road's own mouth. Detected by bearing rather than distance: does any arm open into the
  // angular span this edge sweeps?
  const nodePos = graph.node(junction.node).pos;
  const bearingOf = (p: Vec3): number => Math.atan2(p.z - nodePos.z, p.x - nodePos.x);
  const norm = (angle: number): number => {
    let d = angle % (Math.PI * 2);
    if (d > Math.PI) d -= Math.PI * 2;
    if (d < -Math.PI) d += Math.PI * 2;
    return d;
  };
  const hasHiddenArm = (a: Vec3, b: Vec3): boolean => {
    const span = norm(bearingOf(b) - bearingOf(a));
    return junction.arms.some((arm) => {
      const d = norm(arm.angle - bearingOf(a));
      return span >= 0 ? d > 1e-3 && d < span - 1e-3 : d < -1e-3 && d > span + 1e-3;
    });
  };

  const out: Mesh[] = [];
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i]!;
    const b = ring[(i + 1) % ring.length]!;
    if (isMouth(a, b)) continue;
    // Left unpaved rather than paved wrong: routing the patch around the hidden arm's own
    // mouth needs the corner points of an arm that never made it into `ring` -- more geometry
    // than this closes for. ponytail: skip the corner instead of getting it wrong.
    if (hasHiddenArm(a, b)) continue;

    const dx = b.x - a.x;
    const dz = b.z - a.z;
    const length = Math.hypot(dx, dz);
    if (length < 0.05) continue;
    // Outward normal: perpendicular to the edge, pointing away from the middle of the junction.
    let nx = -dz / length;
    let nz = dx / length;
    if (nx * ((a.x + b.x) / 2 - centroid.x) + nz * ((a.z + b.z) / 2 - centroid.z) < 0) {
      nx = -nx;
      nz = -nz;
    }
    const inner = [
      new Vector3(a.x, a.y + SIDEWALK_LIFT, a.z),
      new Vector3(b.x, b.y + SIDEWALK_LIFT, b.z),
    ];
    const outer = [
      new Vector3(a.x + nx * SIDEWALK_WIDTH, a.y + SIDEWALK_LIFT, a.z + nz * SIDEWALK_WIDTH),
      new Vector3(b.x + nx * SIDEWALK_WIDTH, b.y + SIDEWALK_LIFT, b.z + nz * SIDEWALK_WIDTH),
    ];
    const patch = roadStripMesh(scene, `sidewalk_corner_${junction.node}_${i}`, outer, inner);
    patch.material = paving;
    patch.isPickable = false;
    out.push(patch);
  }
  return out;
}

/**
 * The Traffic view's turn diagram for an ordinary junction: every incoming lane on every arm,
 * curved through to every outgoing lane on every OTHER arm -- the game does not model which
 * turns a lane (or a pedestrian crossing) is actually allowed to make, so this draws every
 * movement that is geometrically possible, the same way a real turning-movement diagram would
 * before restrictions are applied. Shared by cars (`laneCentres`) and foot traffic
 * (`walkCentres`): a road's sidewalks connect to the next one's exactly the same way its
 * carriageway does, just with a different set of lanes and a different exclusion.
 *
 * Which lanes are "incoming" or "outgoing" depends on which end of its own segment this arm sits
 * on: `lanesFor` labels lanes by which way distance increases along the segment, not by which
 * way they face this particular node, so that has to be flipped at the `b` end.
 */
/**
 * The merges and exits of a roundabout: one curve per lane of each arm, into the ring lane that
 * lane feeds and out of the outer one, plus the crossing between ring lanes that leaving from
 * the outer lane forces. Every curve here is the one the traffic actually drives -- both sides
 * build it from `sim/transfers`.
 */
function roundaboutTurnLines(
  scene: Scene,
  graph: RoadGraph,
  junction: JunctionGeometry,
  radii: readonly number[],
  color: Color3,
): LinesMesh[] {
  const ring = ringOf(graph, junction, radii);
  const outer = radii[radii.length - 1]!;
  const lines: LinesMesh[] = [];

  for (const arm of junction.arms) {
    const seg = graph.segment(arm.segment);
    const type = roadType(seg.type);
    if (type.pedestrian) continue;
    const atStart = seg.a === junction.node;
    const lanes = laneCentres(type);

    for (const [i, lane] of lanes.entries()) {
      const joining = atStart ? lane.direction === -1 : lane.direction === 1;
      // A lane joins the ring lane it feeds -- kerb-side onto the outer one, the lane beside the
      // centreline onto the inner. Leaving is only ever done from the outer lane.
      const radius = joining ? ringEntryRadius(radii, laneRank(lanes, lane)) : outer;
      const points = ringJoinPath(graph, ring, arm, lane.offset, radius, joining);
      lines.push(styledLine(scene, `traffic_ring_turn_${junction.node}_${arm.segment}_${i}`, lift(points, MARK_LIFT + 0.02), color));
    }

    if (radii.length > 1 && junction.arms.length > 1) {
      // Aimed at the kerb-side lane of this arm, which is the lane an exit is taken from.
      const kerb = lanes.find((lane) => laneRank(lanes, lane) === 0) ?? lanes[0]!;
      const spiral = ringCrossPath(graph, ring, arm, kerb.offset);
      lines.push(styledLine(scene, `traffic_ring_cross_${junction.node}_${arm.segment}`, lift(spiral, MARK_LIFT + 0.02), color));
    }
  }
  return lines;
}

/** Lifts a path off the surface it was computed on and into Babylon's own vectors. */
function lift(points: readonly Vec3[], by: number): Vector3[] {
  return points.map((p) => new Vector3(p.x, p.y + by, p.z));
}



/**
 * The weave between a road's own lanes: the line a car takes when it moves over, one per
 * direction that actually has two lanes to move between. Same stretch, same easing the traffic
 * uses, from `sim/transfers`.
 */
function laneChangeLines(
  scene: Scene,
  graph: RoadGraph,
  seg: { id: number; length: number },
  type: RoadType,
  from: number,
  to: number,
  color: Color3,
): LinesMesh[] {
  const lanes = laneCentres(type);
  const span = laneChangeSpan(from, to);
  const lines: LinesMesh[] = [];
  for (const direction of [1, -1] as const) {
    const sameWay = lanes.filter((lane) => lane.direction === direction);
    if (sameWay.length < 2) continue;
    const [a, b] = [sameWay[0]!.offset, sameWay[1]!.offset];
    const points = Array.from({ length: 13 }, (_, i) => {
      const t = i / 12;
      const d = direction === 1 ? span.start + (span.end - span.start) * t : span.end - (span.end - span.start) * t;
      const { position, tangent } = graph.pointAt(seg.id, d);
      const n = perpXZ(normalizeXZ(tangent));
      const offset = laneChangeOffset(a, b, t);
      return new Vector3(position.x + n.x * offset, position.y + MARK_LIFT + 0.03, position.z + n.z * offset);
    });
    lines.push(styledLine(scene, `traffic_lane_change_${seg.id}_${direction === 1 ? "out" : "in"}`, points, color));
  }
  return lines;
}


/**
 * The walks people actually make at this node, as opposed to the footway drawn round it: what a
 * crossing has to be answerable to. At a roundabout the footway circles it, so the ways round it
 * are the ways round it; at a junction the loop is closed and contains crossings nobody needs.
 */
function walkCrossings(graph: RoadGraph, junction: JunctionGeometry, junctions: Map<NodeId, JunctionGeometry>): Vec3[][] {
  if (junction.roundabout > 0) return walkTransferPaths(graph, junction, junctions);
  const loop = walkLoop(graph, junction, SIDEWALK_WIDTH, (arm) => roomOn(graph, junctions, arm, junction.node));
  return walkTransfers(graph, junction, loop);
}

/** How much of an arm is road rather than junction: its length less the trim at either end. */
function roomOn(graph: RoadGraph, junctions: Map<NodeId, JunctionGeometry>, arm: JunctionArm, nodeId: NodeId): number {
  const seg = graph.segment(arm.segment);
  const trims = segmentTrims(junctions, graph, arm.segment);
  return seg.length - arm.trim - (seg.a === nodeId ? trims.end : trims.start);
}

/**
 * Every way someone on foot gets across or around a node: the turn from each arm's arriving
 * walkway to every other arm's departing one, or, at a roundabout, the footway that circles it
 * and the step onto that footway from each arm. One list, three uses -- the Traffic view draws
 * it, the walkers walk it, and the zebra crossings are placed where it runs over a carriageway.
 */
function walkTransferPaths(graph: RoadGraph, junction: JunctionGeometry, junctions: Map<NodeId, JunctionGeometry>): Vec3[][] {
  const onFoot = (arm: JunctionArm) => roadType(graph.segment(arm.segment).type);
  const paths: Vec3[][] = [];

  if (junction.roundabout > 0) {
    const ring = ringOf(graph, junction, ringLaneRadii(graph, junction.node, junction.roundabout));
    const radius = walkRingRadius(ring, SIDEWALK_WIDTH);
    paths.push(Array.from({ length: 65 }, (_, i) => onRing(ring, (i / 64) * Math.PI * 2, radius)));
    for (const arm of junction.arms) {
      if (onFoot(arm).highway) continue; // a guardrail where the footway would be
      for (const walk of walkCentres(onFoot(arm), SIDEWALK_WIDTH)) {
        paths.push(ringWalkJoin(graph, ring, arm, walk.offset, radius));
      }
    }
    return paths;
  }

  const loop = walkLoop(graph, junction, SIDEWALK_WIDTH, (arm) => roomOn(graph, junctions, arm, junction.node));
  return loop.points.length > 0 ? [[...loop.points, loop.points[0]!]] : [];
}


function junctionTurnLines(scene: Scene, graph: RoadGraph, junction: JunctionGeometry, color: Color3): LinesMesh[] {
  interface Port {
    readonly position: Vec3;
    readonly armSegment: number;
  }
  const incoming: Port[] = [];
  const outgoing: Port[] = [];

  for (const arm of junction.arms) {
    const seg = graph.segment(arm.segment);
    const type = roadType(seg.type);
    if (type.pedestrian) continue; // its own foot transfers are drawn, not a turn diagram
    const atStart = seg.a === junction.node;
    for (const lane of laneCentres(type)) {
      const arrivingHere = atStart ? lane.direction === -1 : lane.direction === 1;
      (arrivingHere ? incoming : outgoing).push({
        position: armPort(graph, junction.node, arm, lane.offset),
        armSegment: arm.segment,
      });
    }
  }

  const centre = graph.node(junction.node).pos;
  const lines: LinesMesh[] = [];
  for (const [i, from] of incoming.entries()) {
    for (const [j, to] of outgoing.entries()) {
      if (from.armSegment === to.armSegment) continue; // no U-turn back onto the arm it came from
      const points = junctionTurnPath(centre, from.position, to.position);
      lines.push(styledLine(scene, `traffic_turn_${junction.node}_${i}_${j}`, lift(points, MARK_LIFT + 0.02), color));
    }
  }
  return lines;
}

/**
 * The gaps between the arms, each swept into a strip of footway. Each arm blocks the angle its
 * own carriageway and sidewalks subtend at the ring, so the footway meets them rather than
 * crossing them.
 */
function footwayArcs(
  scene: Scene,
  graph: RoadGraph,
  junction: JunctionGeometry,
  centre: { x: number; y: number; z: number },
  outer: number,
  elevationAt: (angle: number) => number,
  paving: StandardMaterial,
): Mesh[] {
  const blocked = junction.arms
    .map((arm) => {
      const width = roadType(graph.segment(arm.segment).type).width / 2 + SIDEWALK_WIDTH;
      return { angle: arm.angle, spread: Math.asin(Math.min(0.99, width / outer)) };
    })
    .sort((l, r) => l.angle - r.angle);
  if (blocked.length === 0) return [];

  const out: Mesh[] = [];
  for (const [i, arm] of blocked.entries()) {
    const next = blocked[(i + 1) % blocked.length]!;
    const from = arm.angle + arm.spread;
    let to = next.angle - next.spread;
    while (to < from) to += Math.PI * 2;
    if (to - from < 0.05) continue; // arms nearly touching: no room for a walkway between them

    const steps = Math.max(2, Math.ceil((to - from) / 0.12));
    const near: Vector3[] = [];
    const far: Vector3[] = [];
    for (let s = 0; s <= steps; s++) {
      const angle = from + ((to - from) * s) / steps;
      const cos = Math.cos(angle);
      const sin = Math.sin(angle);
      const y = elevationAt(angle) + SIDEWALK_LIFT;
      near.push(new Vector3(centre.x + cos * outer, y, centre.z + sin * outer));
      far.push(new Vector3(centre.x + cos * (outer + SIDEWALK_WIDTH), y, centre.z + sin * (outer + SIDEWALK_WIDTH)));
    }
    const walk = roadStripMesh(scene, `roundabout_walk_${junction.node}_${i}`, far, near);
    walk.material = paving;
    walk.isPickable = false;
    out.push(walk);
  }
  return out;
}

function styledLine(scene: Scene, name: string, points: Vector3[], color: Color3, close = false): LinesMesh {
  const mesh = MeshBuilder.CreateLines(name, { points: close ? [...points, points[0]!] : points }, scene);
  mesh.color = color;
  mesh.isPickable = false;
  return mesh;
}

function pointsTouchBounds(points: readonly Vec3[], bounds: TerrainBounds): boolean {
  return points.some((p) => p.x >= bounds.minX && p.x <= bounds.maxX && p.z >= bounds.minZ && p.z <= bounds.maxZ);
}

export function segmentMeshTouchesBounds(points: readonly Vec3[], type: Pick<RoadType, "width" | "highway" | "pedestrian">, bounds: TerrainBounds): boolean {
  const pad = type.highway || type.pedestrian ? type.width / 2 : type.width / 2 + SIDEWALK_WIDTH;
  const expanded = { minX: bounds.minX - pad, maxX: bounds.maxX + pad, minZ: bounds.minZ - pad, maxZ: bounds.maxZ + pad };
  for (let i = 0; i < points.length; i++) {
    const a = points[i]!;
    if (pointTouchesBounds(a, expanded)) return true;
    const b = points[i + 1];
    if (b && segmentTouchesBounds(a, b, expanded)) return true;
  }
  return false;
}

function junctionTouchesBounds(junction: JunctionGeometry, bounds: TerrainBounds): boolean {
  return pointsTouchBounds(junction.ring, bounds) || junction.arms.some((arm) => pointsTouchBounds([arm.cornerLow, arm.cornerHigh], bounds));
}

function meshTouchesDirty(segmentsById: Map<number, { samples: readonly Vec3[]; type: string }>, mesh: Mesh | LinesMesh, bounds: TerrainBounds): boolean {
  const id = segmentIdFromMeshName(mesh.name);
  if (id !== null) {
    const segment = segmentsById.get(id);
    if (!segment) return true;
    return segmentMeshTouchesBounds(segment.samples, roadType(segment.type), bounds);
  }
  mesh.computeWorldMatrix(true);
  const box = mesh.getBoundingInfo().boundingBox;
  return box.maximumWorld.x >= bounds.minX && box.minimumWorld.x <= bounds.maxX && box.maximumWorld.z >= bounds.minZ && box.minimumWorld.z <= bounds.maxZ;
}

function pointTouchesBounds(p: Vec3, bounds: TerrainBounds): boolean {
  return p.x >= bounds.minX && p.x <= bounds.maxX && p.z >= bounds.minZ && p.z <= bounds.maxZ;
}

function segmentTouchesBounds(a: Vec3, b: Vec3, bounds: TerrainBounds): boolean {
  if (Math.max(a.x, b.x) < bounds.minX || Math.min(a.x, b.x) > bounds.maxX || Math.max(a.z, b.z) < bounds.minZ || Math.min(a.z, b.z) > bounds.maxZ) return false;
  return (
    linesIntersect(a, b, { x: bounds.minX, y: 0, z: bounds.minZ }, { x: bounds.maxX, y: 0, z: bounds.minZ }) ||
    linesIntersect(a, b, { x: bounds.maxX, y: 0, z: bounds.minZ }, { x: bounds.maxX, y: 0, z: bounds.maxZ }) ||
    linesIntersect(a, b, { x: bounds.maxX, y: 0, z: bounds.maxZ }, { x: bounds.minX, y: 0, z: bounds.maxZ }) ||
    linesIntersect(a, b, { x: bounds.minX, y: 0, z: bounds.maxZ }, { x: bounds.minX, y: 0, z: bounds.minZ })
  );
}

function linesIntersect(a: Vec3, b: Vec3, c: Vec3, d: Vec3): boolean {
  const side = (p: Vec3, q: Vec3, r: Vec3) => Math.sign((q.x - p.x) * (r.z - p.z) - (q.z - p.z) * (r.x - p.x));
  const abC = side(a, b, c);
  const abD = side(a, b, d);
  const cdA = side(c, d, a);
  const cdB = side(c, d, b);
  return abC !== abD && cdA !== cdB;
}

function segmentIdFromMeshName(name: string): number | null {
  const match = /^(?:road|curb_[lr]|guardrail_[lr]|sidewalk_[lr]|lane|traffic_lane|traffic_walk|traffic_lane_change|tunnel_trace|tunnel)_(\d+)/.exec(name);
  return match ? Number(match[1]) : null;
}

/** `offset` moves the sampled line sideways from the centreline, for a lane drawn off-centre. */
function pointsBetween(
  graph: RoadGraph,
  id: number,
  from: number,
  to: number,
  steps: number,
  lift: number,
  offset = 0,
): Vector3[] {
  const points: Vector3[] = [];
  for (let i = 0; i <= steps; i++) {
    const d = from + ((to - from) * i) / steps;
    const { position, tangent } = graph.pointAt(id, d);
    const y = Math.max(position.y, terrainHeight(position.x, position.z)) + lift;
    if (offset === 0) {
      points.push(new Vector3(position.x, y, position.z));
    } else {
      const n = perpXZ(normalizeXZ(tangent));
      points.push(new Vector3(position.x + n.x * offset, y, position.z + n.z * offset));
    }
  }
  return points;
}

function tunnelMesh(scene: Scene, name: string, graph: RoadGraph, id: number, steps: number, width: number): { shell: Mesh; interior: Mesh } {
  const seg = graph.segment(id);
  const inner = tunnelSection(width);
  const outer = tunnelSection(width + 8).map((p) => ({ x: p.x, y: p.y + 1.5 }));
  const shellPositions: number[] = [];
  const interiorPositions: number[] = [];
  for (let i = 0; i <= steps; i++) {
    const { position, tangent } = graph.pointAt(id, (seg.length * i) / steps);
    const n = perpXZ(normalizeXZ(tangent));
    const y = position.y + ROAD_LIFT;
    for (const p of outer) shellPositions.push(position.x + n.x * p.x, y + p.y, position.z + n.z * p.x);
    for (const p of inner) interiorPositions.push(position.x + n.x * p.x, y + p.y, position.z + n.z * p.x);
  }
  const shellIndices = tunnelStripIndices(outer.length, steps, false);
  const interiorIndices = tunnelStripIndices(inner.length, steps, true);
  return {
    shell: vertexMesh(scene, `${name}_shell`, shellPositions, shellIndices),
    interior: vertexMesh(scene, `${name}_interior`, interiorPositions, interiorIndices),
  };
}

export function tunnelStripIndices(count: number, steps: number, flip: boolean): number[] {
  const indices: number[] = [];
  for (let i = 0; i < steps; i++) {
    const a = i * count;
    const b = a + count;
    for (let j = 0; j < count - 1; j++) {
      if (flip) indices.push(a + j, a + j + 1, b + j, a + j + 1, b + j + 1, b + j);
      else indices.push(a + j, b + j, a + j + 1, a + j + 1, b + j, b + j + 1);
    }
  }
  return indices;
}

function vertexMesh(scene: Scene, name: string, positions: number[], indices: number[]): Mesh {
  const mesh = new MeshClass(name, scene);
  const data = new VertexData();
  data.positions = positions;
  data.indices = indices;
  const normals: number[] = [];
  VertexData.ComputeNormals(positions, indices, normals);
  data.normals = normals;
  data.applyToMesh(mesh);
  return mesh;
}

export function tunnelSection(width: number): { x: number; y: number }[] {
  const gateWidth = width + 8;
  const wall = 3;
  const arch = 5;
  const half = gateWidth / 2;
  return [
    { x: -half, y: 0 },
    { x: -half, y: wall },
    ...Array.from({ length: 7 }, (_, i) => {
      const x = -half + (gateWidth * i) / 6;
      return { x, y: wall + arch * Math.sqrt(1 - (x / half) ** 2) };
    }),
    { x: half, y: wall },
    { x: half, y: 0 },
  ];
}

function tunnelPortals(
  scene: Scene,
  graph: RoadGraph,
  id: number,
  width: number,
  material: StandardMaterial,
  color: Color3,
): (Mesh | LinesMesh)[] {
  const seg = graph.segment(id);
  return [
    ...tunnelPortal(scene, graph, id, 0, width, 1, material, color),
    ...tunnelPortal(scene, graph, id, seg.length, width, -1, material, color),
  ];
}

function tunnelPortal(
  scene: Scene,
  graph: RoadGraph,
  id: number,
  distance: number,
  width: number,
  direction: 1 | -1,
  material: StandardMaterial,
  color: Color3,
): (Mesh | LinesMesh)[] {
  const { position, tangent } = graph.pointAt(id, distance);
  const y = terrainHeight(position.x, position.z) + MARK_LIFT;
  const exterior = portalExterior(scene, `tunnel_headwall_${id}_${distance}`, position, tangent, width, direction, y);
  for (const mesh of exterior) {
    mesh.material = material;
    mesh.isPickable = false;
  }

  const portal = portalMesh(scene, `tunnel_portal_${id}_${distance}`, position, tangent, width, direction, y);
  portal.material = material;
  portal.isPickable = false;

  const lip = portalOutline(position, tangent, width, y);
  return [...exterior, portal, styledLine(scene, `tunnel_lip_${id}_${distance}`, lip, color)];
}

function portalExterior(
  scene: Scene,
  name: string,
  center: { x: number; z: number },
  tangent: { x: number; z: number },
  width: number,
  direction: 1 | -1,
  y: number,
): Mesh[] {
  const gate = width + 8;
  const side = 5;
  const height = 9;
  const top = 3;
  const depth = 5;
  const rotation = Math.atan2(tangent.x * direction, tangent.z * direction);
  const n = perpXZ(normalizeXZ({ x: tangent.x, y: 0, z: tangent.z }));
  const block = (label: string, x: number, boxWidth: number, boxHeight: number, cy: number) => {
    const mesh = MeshBuilder.CreateBox(`${name}_${label}`, { width: boxWidth, height: boxHeight, depth }, scene);
    mesh.position.set(center.x + n.x * x, cy, center.z + n.z * x);
    mesh.rotation.y = rotation;
    return mesh;
  };
  return [
    block("left", -gate / 2 - side / 2, side, height, y + height / 2),
    block("right", gate / 2 + side / 2, side, height, y + height / 2),
    block("top", 0, gate + side * 2, top, y + height + top / 2),
  ];
}

function portalMesh(
  scene: Scene,
  name: string,
  center: { x: number; z: number },
  tangent: { x: number; z: number },
  width: number,
  direction: 1 | -1,
  y: number,
): Mesh {
  const t = normalizeXZ({ x: tangent.x * direction, y: 0, z: tangent.z * direction });
  const n = perpXZ(t);
  const inner = tunnelSection(width);
  const outer = tunnelSection(width + 8).map((p) => ({ x: p.x, y: p.y + 1.5 }));
  const positions: number[] = [];
  for (const d of [-1.4, 1.4]) {
    for (const section of [outer, inner]) {
      for (const p of section) positions.push(center.x + n.x * p.x + t.x * d, y + p.y, center.z + n.z * p.x + t.z * d);
    }
  }
  const indices: number[] = [];
  const count = inner.length;
  const frontOuter = 0;
  const frontInner = count;
  const backOuter = count * 2;
  const backInner = count * 3;
  for (let i = 0; i < count - 1; i++) {
    indices.push(frontOuter + i, frontOuter + i + 1, frontInner + i, frontOuter + i + 1, frontInner + i + 1, frontInner + i);
    indices.push(backOuter + i, backInner + i, backOuter + i + 1, backOuter + i + 1, backInner + i, backInner + i + 1);
    indices.push(frontOuter + i, backOuter + i, frontOuter + i + 1, frontOuter + i + 1, backOuter + i, backOuter + i + 1);
    indices.push(frontInner + i, frontInner + i + 1, backInner + i, frontInner + i + 1, backInner + i + 1, backInner + i);
  }
  const mesh = new MeshClass(name, scene);
  const data = new VertexData();
  data.positions = positions;
  data.indices = indices;
  const normals: number[] = [];
  VertexData.ComputeNormals(positions, indices, normals);
  data.normals = normals;
  data.applyToMesh(mesh);
  return mesh;
}

export function portalOutline(center: { x: number; z: number }, tangent: { x: number; z: number }, width: number, y: number): Vector3[] {
  const n = perpXZ(normalizeXZ({ x: tangent.x, y: 0, z: tangent.z }));
  return tunnelSection(width).map((p) => new Vector3(center.x + n.x * p.x, y + p.y, center.z + n.z * p.x));
}

function roadStripMesh(scene: Scene, name: string, left: Vector3[], right: Vector3[]): Mesh {
  const positions: number[] = [];
  const indices: number[] = [];
  for (let i = 0; i < left.length; i++) positions.push(left[i]!.x, left[i]!.y, left[i]!.z, right[i]!.x, right[i]!.y, right[i]!.z);
  for (let i = 0; i < left.length - 1; i++) {
    const a = i * 2;
    indices.push(a, a + 1, a + 2, a + 1, a + 3, a + 2);
  }
  const mesh = new MeshClass(name, scene);
  const data = new VertexData();
  data.positions = positions;
  data.indices = indices;
  data.normals = Array.from({ length: positions.length / 3 }, () => [0, 1, 0]).flat();
  data.applyToMesh(mesh);
  return mesh;
}

/**
 * A triangle fan from the ring's centroid. The ring is convex, so a fan tessellates it
 * exactly -- no earcut, no dependency.
 */
function junctionMesh(scene: Scene, junction: JunctionGeometry): Mesh | null {
  const ring = junction.ring;
  if (ring.length < 3) return null;

  let cx = 0;
  let cy = 0;
  let cz = 0;
  for (const p of ring) {
    cx += p.x;
    cy += p.y;
    cz += p.z;
  }
  cx /= ring.length;
  cy /= ring.length;
  cz /= ring.length;

  const positions: number[] = [cx, cy + ROAD_LIFT, cz];
  for (const p of ring) positions.push(p.x, p.y + ROAD_LIFT, p.z);

  const indices: number[] = [];
  for (let i = 0; i < ring.length; i++) {
    indices.push(0, 1 + i, 1 + ((i + 1) % ring.length));
  }

  const mesh = new MeshClass(`junction_${junction.node}`, scene);
  const data = new VertexData();
  data.positions = positions;
  // Wound both ways, because the hull's winding can come out either way and a junction
  // culled from above is a hole. The normals are set explicitly rather than derived: a
  // horizontal polygon's normal is known, and deriving it from two windings cancels out.
  data.indices = [...indices, ...indices.slice().reverse()];
  data.normals = Array.from({ length: positions.length / 3 }, () => [0, 1, 0]).flat();
  data.applyToMesh(mesh);
  return mesh;
}
