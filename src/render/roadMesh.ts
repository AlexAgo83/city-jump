/** Lifted off the ground so the road wins the depth fight with it. */
export const ROAD_LIFT = 0.06;

/** Footway either side of a carriageway. Fits inside SLOT.setback, so no building has to move. */
export const SIDEWALK_WIDTH = 2.6;
/** Kerb height. Enough to read as a step, low enough that nothing has to climb it. */
export const SIDEWALK_LIFT = ROAD_LIFT + 0.18;

/** Zebra stripes: painted on the carriageway just outside the junction each arm runs into. */
const CROSSING_DEPTH = 4;
const CROSSING_GAP = 1.6;
const STRIPE_WIDTH = 0.9;
const MARK_LIFT = ROAD_LIFT + 0.05;

/**
 * Turns the graph into road surface. Every mesh here is derived: `rebuild` disposes what
 * it made and builds again from the graph, and nothing else ever touches these meshes.
 */
export function createRoadRenderer(scene: Scene, graph: RoadGraph) {
  const material = new StandardMaterial("road", scene);
  material.diffuseColor = new Color3(0.18, 0.18, 0.19);
  // A footpath in the same asphalt as a street reads as a street. Paving reads as somewhere to walk.
  const pavingMaterial = new StandardMaterial("paving", scene);
  pavingMaterial.diffuseColor = new Color3(0.56, 0.53, 0.48);
  pavingMaterial.specularColor = Color3.Black();
  // Footway strips are generated by several builders -- straight runs, junction corners, arcs
  // around a ring -- and their winding depends on which way each one walks its points. They are
  // all flat and seen from above, so drawing both faces is cheaper than getting every winding
  // right. ponytail: one flag, not four orientation arguments.
  pavingMaterial.backFaceCulling = false;
  const paintMaterial = new StandardMaterial("road_paint", scene);
  paintMaterial.diffuseColor = new Color3(0.88, 0.88, 0.85);
  paintMaterial.specularColor = Color3.Black();
  material.specularColor = Color3.Black();
  const portalMaterial = new StandardMaterial("tunnel_portal", scene);
  portalMaterial.diffuseColor = new Color3(0.26, 0.25, 0.23);
  portalMaterial.specularColor = Color3.Black();
  const tubeMaterial = new StandardMaterial("tunnel_tube", scene);
  tubeMaterial.diffuseColor = new Color3(0.06, 0.06, 0.055);
  tubeMaterial.emissiveColor = new Color3(0.01, 0.008, 0.006);
  tubeMaterial.specularColor = Color3.Black();
  const curb = new Color3(0.52, 0.55, 0.53);
  const lane = new Color3(0.86, 0.78, 0.48);
  const tunnel = new Color3(0.58, 0.55, 0.49);

  let meshes: (Mesh | LinesMesh)[] = [];

  function rebuild(): void {
    for (const mesh of meshes) mesh.dispose();
    meshes = [];

    const junctions = allJunctions(graph);

    for (const seg of graph.allSegments()) {
      const type = roadType(seg.type);
      if (type.tunnelDepth) {
        const steps = Math.max(4, Math.ceil(seg.length / 8));
        const trace = pointsBetween(graph, seg.id, 0, seg.length, steps, MARK_LIFT);
        const line = MeshBuilder.CreateDashedLines(`tunnel_trace_${seg.id}`, { points: trace, dashSize: 8, gapSize: 5 }, scene);
        line.color = tunnel;
        line.isPickable = false;

        const tube = tunnelMesh(scene, `tunnel_${seg.id}`, graph, seg.id, steps, type.width);
        tube.shell.material = portalMaterial;
        tube.interior.material = tubeMaterial;
        tube.shell.isPickable = false;
        tube.interior.isPickable = false;
        meshes.push(line, tube.shell, tube.interior);
        meshes.push(...tunnelPortals(scene, graph, seg.id, type.width, portalMaterial, tunnel));
        continue;
      }

      const half = type.width / 2;
      const isAvenue = seg.type === "avenue";
      // The surface stops short of each junction; the junction polygon closes the gap.
      const { start, end } = segmentTrims(junctions, graph, seg.id);
      const from = start;
      const to = seg.length - end;
      if (to - from < 0.25) continue; // wholly inside its junctions

      const left: Vector3[] = [];
      const right: Vector3[] = [];
      const steps = Math.max(2, Math.ceil((to - from) / 2));
      for (let i = 0; i <= steps; i++) {
        const d = from + ((to - from) * i) / steps;
        const { position, tangent } = graph.pointAt(seg.id, d);
        const n = perpXZ(normalizeXZ(tangent));
        left.push(new Vector3(position.x + n.x * half, position.y + ROAD_LIFT, position.z + n.z * half));
        right.push(new Vector3(position.x - n.x * half, position.y + ROAD_LIFT, position.z - n.z * half));
      }

      const ribbon = roadStripMesh(scene, `road_${seg.id}`, left, right);
      ribbon.material = type.pedestrian ? pavingMaterial : material;
      ribbon.isPickable = false;
      meshes.push(ribbon);
      meshes.push(styledLine(scene, `curb_l_${seg.id}`, left, curb), styledLine(scene, `curb_r_${seg.id}`, right, curb));

      // A footway either side, stepped up from the carriageway. A path is already all footway.
      if (!type.pedestrian) {
        const outerLeft: Vector3[] = [];
        const outerRight: Vector3[] = [];
        const innerLeft: Vector3[] = [];
        const innerRight: Vector3[] = [];
        for (let i = 0; i <= steps; i++) {
          const d = from + ((to - from) * i) / steps;
          const { position, tangent } = graph.pointAt(seg.id, d);
          const n = perpXZ(normalizeXZ(tangent));
          const y = position.y + SIDEWALK_LIFT;
          const out = half + SIDEWALK_WIDTH;
          innerLeft.push(new Vector3(position.x + n.x * half, y, position.z + n.z * half));
          outerLeft.push(new Vector3(position.x + n.x * out, y, position.z + n.z * out));
          innerRight.push(new Vector3(position.x - n.x * half, y, position.z - n.z * half));
          outerRight.push(new Vector3(position.x - n.x * out, y, position.z - n.z * out));
        }
        const walkLeft = roadStripMesh(scene, `sidewalk_l_${seg.id}`, outerLeft, innerLeft);
        const walkRight = roadStripMesh(scene, `sidewalk_r_${seg.id}`, innerRight, outerRight);
        for (const walk of [walkLeft, walkRight]) {
          walk.material = pavingMaterial;
          walk.isPickable = false;
          meshes.push(walk);
        }
      }
      if (isAvenue) {
        const center = pointsBetween(graph, seg.id, from, to, steps, MARK_LIFT);
        meshes.push(styledLine(scene, `lane_${seg.id}`, center, lane));
      }
    }

    // A crossing on every arm of every junction, so there is a marked way over each road.
    for (const junction of junctions.values()) {
      for (const arm of junction.arms) {
        const seg = graph.segment(arm.segment);
        const type = roadType(seg.type);
        if (type.tunnelDepth || type.pedestrian) continue;
        meshes.push(...crossingMeshes(scene, graph, junction.node, arm, type.width, paintMaterial));
      }
    }

    for (const junction of junctions.values()) {
      if (junction.roundabout > 0) {
        meshes.push(...roundaboutMeshes(scene, graph, junction, material, curb, pavingMaterial));
        continue;
      }
      const mesh = junctionMesh(scene, junction);
      if (!mesh) continue;
      mesh.material = material;
      mesh.isPickable = false;
      meshes.push(mesh);
      // The footways have to close around the junction too, or every sidewalk stops dead at it.
      meshes.push(...junctionFootway(scene, graph, junction, pavingMaterial));
    }
  }

  return { rebuild, material };
}

/**
 * The ring itself: a flat annulus from the kerb of the island out to where the arms were trimmed.
 * Carriageway width is the widest road meeting the node, which is the same reference the radius
 * takes. ponytail: a lathe over two points, not a swept road built from the graph.
 */
/**
 * One zebra across an arm, laid just beyond where the junction surface ends. Stripes run along
 * the road, so they read as a crossing rather than as lane markings.
 * ponytail: a strip mesh per stripe, reusing the ribbon builder the roads already use.
 */
function crossingMeshes(
  scene: Scene,
  graph: RoadGraph,
  nodeId: NodeId,
  arm: JunctionArm,
  width: number,
  paint: StandardMaterial,
): Mesh[] {
  const seg = graph.segment(arm.segment);
  const atStart = seg.a === nodeId;
  const near = arm.trim + CROSSING_GAP;
  const far = near + CROSSING_DEPTH;
  // Not if the road is too short to hold one clear of its other end.
  if (far > seg.length - arm.trim) return [];

  const half = width / 2;
  const stripes = Math.max(2, Math.floor(width / (STRIPE_WIDTH * 2)));
  const pitch = width / stripes;
  const out: Mesh[] = [];

  for (let i = 0; i < stripes; i++) {
    const centre = -half + pitch * (i + 0.5);
    const left: Vector3[] = [];
    const right: Vector3[] = [];
    for (const d of [near, far]) {
      const along = atStart ? d : seg.length - d;
      const { position, tangent } = graph.pointAt(arm.segment, along);
      const n = perpXZ(normalizeXZ(tangent));
      const lo = centre - STRIPE_WIDTH / 2;
      const hi = centre + STRIPE_WIDTH / 2;
      left.push(new Vector3(position.x + n.x * lo, position.y + MARK_LIFT, position.z + n.z * lo));
      right.push(new Vector3(position.x + n.x * hi, position.y + MARK_LIFT, position.z + n.z * hi));
    }
    const stripe = roadStripMesh(scene, `crossing_${arm.segment}_${nodeId}_${i}`, left, right);
    stripe.material = paint;
    stripe.isPickable = false;
    out.push(stripe);
  }
  return out;
}

function roundaboutMeshes(
  scene: Scene,
  graph: RoadGraph,
  junction: JunctionGeometry,
  surface: StandardMaterial,
  kerb: Color3,
  paving: StandardMaterial,
): Mesh[] {
  const centre = graph.node(junction.node).pos;
  const outer = junction.roundabout;
  const reference = widestIncidentRoad(graph, junction.node);
  const lane = Math.max(6, reference?.width ?? 0);
  const inner = Math.max(3, outer - lane);
  // A ring between footpaths is paved, like the paths themselves.
  const onFoot = reference?.pedestrian === true;

  const ring = MeshBuilder.CreateLathe(
    `roundabout_${junction.node}`,
    { shape: [new Vector3(inner, 0, 0), new Vector3(outer, 0, 0)], tessellation: 40, sideOrientation: MeshClass.DOUBLESIDE },
    scene,
  );
  // A little more clearance than an ordinary road: the ring's disc is much wider than any
  // single road is, so it has more terrain to clear underneath it, and a couple of centimetres
  // extra here is cheap insurance against whatever the flatten still leaves imperfect.
  ring.position.set(centre.x, centre.y + ROAD_LIFT + 0.15, centre.z);
  ring.material = onFoot ? paving : surface;
  ring.isPickable = false;

  const circle = (radius: number): Vector3[] =>
    Array.from({ length: 41 }, (_, i) => {
      const angle = (i / 40) * Math.PI * 2;
      return new Vector3(centre.x + Math.cos(angle) * radius, centre.y + MARK_LIFT, centre.z + Math.sin(angle) * radius);
    });

  return [
    ring,
    // A footway ring outside it, but broken where the arms come in: a full lathe would lay a band
    // straight across every road meeting the roundabout. A path is all footway already.
    ...(onFoot ? [] : footwayArcs(scene, graph, junction, centre, outer, paving)),
    styledLine(scene, `roundabout_kerb_out_${junction.node}`, circle(outer), kerb),
    styledLine(scene, `roundabout_kerb_in_${junction.node}`, circle(inner), kerb),
  ];
}

/**
 * Closes the footway around an ordinary junction. The junction polygon already has exactly the
 * right outline: each edge is either the mouth of a road, or a stretch of kerb between two roads.
 * Sweeping every non-mouth edge outwards gives the corner paving, and cannot cut across the
 * junction the way joining arm corners pairwise could.
 * ponytail: walk the hull that is already computed, rather than deriving a second polygon.
 */
function junctionFootway(
  scene: Scene,
  graph: RoadGraph,
  junction: JunctionGeometry,
  paving: StandardMaterial,
): Mesh[] {
  const ring = junction.ring;
  if (ring.length < 3) return [];

  const centroid = ring.reduce((sum, p) => ({ x: sum.x + p.x / ring.length, z: sum.z + p.z / ring.length }), {
    x: 0,
    z: 0,
  });
  // Two neighbouring arms each compute their shared corner independently, from their own
  // (possibly curved) centreline -- they land within a few centimetres of each other, not
  // exactly on top. A tighter epsilon here misses that match, misreads the mouth as a kerb
  // gap, and pastes a sidewalk patch straight onto the carriageway.
  const same = (a: Vec3, b: Vec3): boolean => Math.hypot(a.x - b.x, a.z - b.z) < 0.15;
  /** True when this edge is where a road opens onto the junction, which must stay clear. */
  const isMouth = (a: Vec3, b: Vec3): boolean =>
    junction.arms.some(
      (arm) =>
        (same(a, arm.cornerLow) && same(b, arm.cornerHigh)) || (same(a, arm.cornerHigh) && same(b, arm.cornerLow)),
    );

  // A narrower road can meet this node without ever reaching the hull -- its corners sit
  // inside the ring, pulled behind the wider roads either side of it. The kerb edge that
  // "closes" the gap those wide roads leave then actually runs straight over that narrower
  // road's own mouth. Detected by bearing rather than distance: does any arm open into the
  // angular span this edge sweeps?
  const nodePos = graph.node(junction.node).pos;
  const bearingOf = (p: Vec3): number => Math.atan2(p.z - nodePos.z, p.x - nodePos.x);
  const norm = (angle: number): number => {
    let d = angle % (Math.PI * 2);
    if (d > Math.PI) d -= Math.PI * 2;
    if (d < -Math.PI) d += Math.PI * 2;
    return d;
  };
  const hasHiddenArm = (a: Vec3, b: Vec3): boolean => {
    const span = norm(bearingOf(b) - bearingOf(a));
    return junction.arms.some((arm) => {
      const d = norm(arm.angle - bearingOf(a));
      return span >= 0 ? d > 1e-3 && d < span - 1e-3 : d < -1e-3 && d > span + 1e-3;
    });
  };

  const out: Mesh[] = [];
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i]!;
    const b = ring[(i + 1) % ring.length]!;
    if (isMouth(a, b)) continue;
    // Left unpaved rather than paved wrong: routing the patch around the hidden arm's own
    // mouth needs the corner points of an arm that never made it into `ring` -- more geometry
    // than this closes for. ponytail: skip the corner instead of getting it wrong.
    if (hasHiddenArm(a, b)) continue;

    const dx = b.x - a.x;
    const dz = b.z - a.z;
    const length = Math.hypot(dx, dz);
    if (length < 0.05) continue;
    // Outward normal: perpendicular to the edge, pointing away from the middle of the junction.
    let nx = -dz / length;
    let nz = dx / length;
    if (nx * ((a.x + b.x) / 2 - centroid.x) + nz * ((a.z + b.z) / 2 - centroid.z) < 0) {
      nx = -nx;
      nz = -nz;
    }
    const inner = [
      new Vector3(a.x, a.y + SIDEWALK_LIFT, a.z),
      new Vector3(b.x, b.y + SIDEWALK_LIFT, b.z),
    ];
    const outer = [
      new Vector3(a.x + nx * SIDEWALK_WIDTH, a.y + SIDEWALK_LIFT, a.z + nz * SIDEWALK_WIDTH),
      new Vector3(b.x + nx * SIDEWALK_WIDTH, b.y + SIDEWALK_LIFT, b.z + nz * SIDEWALK_WIDTH),
    ];
    const patch = roadStripMesh(scene, `sidewalk_corner_${junction.node}_${i}`, outer, inner);
    patch.material = paving;
    patch.isPickable = false;
    out.push(patch);
  }
  return out;
}

/**
 * The gaps between the arms, each swept into a strip of footway. Each arm blocks the angle its
 * own carriageway and sidewalks subtend at the ring, so the footway meets them rather than
 * crossing them.
 */
function footwayArcs(
  scene: Scene,
  graph: RoadGraph,
  junction: JunctionGeometry,
  centre: { x: number; y: number; z: number },
  outer: number,
  paving: StandardMaterial,
): Mesh[] {
  const blocked = junction.arms
    .map((arm) => {
      const width = roadType(graph.segment(arm.segment).type).width / 2 + SIDEWALK_WIDTH;
      return { angle: arm.angle, spread: Math.asin(Math.min(0.99, width / outer)) };
    })
    .sort((l, r) => l.angle - r.angle);
  if (blocked.length === 0) return [];

  const out: Mesh[] = [];
  const y = centre.y + SIDEWALK_LIFT;
  for (const [i, arm] of blocked.entries()) {
    const next = blocked[(i + 1) % blocked.length]!;
    const from = arm.angle + arm.spread;
    let to = next.angle - next.spread;
    while (to < from) to += Math.PI * 2;
    if (to - from < 0.05) continue; // arms nearly touching: no room for a walkway between them

    const steps = Math.max(2, Math.ceil((to - from) / 0.12));
    const near: Vector3[] = [];
    const far: Vector3[] = [];
    for (let s = 0; s <= steps; s++) {
      const angle = from + ((to - from) * s) / steps;
      const cos = Math.cos(angle);
      const sin = Math.sin(angle);
      near.push(new Vector3(centre.x + cos * outer, y, centre.z + sin * outer));
      far.push(new Vector3(centre.x + cos * (outer + SIDEWALK_WIDTH), y, centre.z + sin * (outer + SIDEWALK_WIDTH)));
    }
    const walk = roadStripMesh(scene, `roundabout_walk_${junction.node}_${i}`, far, near);
    walk.material = paving;
    walk.isPickable = false;
    out.push(walk);
  }
  return out;
}

function styledLine(scene: Scene, name: string, points: Vector3[], color: Color3, close = false): LinesMesh {
  const mesh = MeshBuilder.CreateLines(name, { points: close ? [...points, points[0]!] : points }, scene);
  mesh.color = color;
  mesh.isPickable = false;
  return mesh;
}

function pointsBetween(graph: RoadGraph, id: number, from: number, to: number, steps: number, lift: number): Vector3[] {
  const points: Vector3[] = [];
  for (let i = 0; i <= steps; i++) {
    const d = from + ((to - from) * i) / steps;
    const { position } = graph.pointAt(id, d);
    points.push(new Vector3(position.x, Math.max(position.y, terrainHeight(position.x, position.z)) + lift, position.z));
  }
  return points;
}

function tunnelMesh(scene: Scene, name: string, graph: RoadGraph, id: number, steps: number, width: number): { shell: Mesh; interior: Mesh } {
  const seg = graph.segment(id);
  const inner = tunnelSection(width);
  const outer = tunnelSection(width + 8).map((p) => ({ x: p.x, y: p.y + 1.5 }));
  const shellPositions: number[] = [];
  const interiorPositions: number[] = [];
  for (let i = 0; i <= steps; i++) {
    const { position, tangent } = graph.pointAt(id, (seg.length * i) / steps);
    const n = perpXZ(normalizeXZ(tangent));
    const y = position.y + ROAD_LIFT;
    for (const p of outer) shellPositions.push(position.x + n.x * p.x, y + p.y, position.z + n.z * p.x);
    for (const p of inner) interiorPositions.push(position.x + n.x * p.x, y + p.y, position.z + n.z * p.x);
  }
  const shellIndices = tunnelStripIndices(outer.length, steps, false);
  const interiorIndices = tunnelStripIndices(inner.length, steps, true);
  return {
    shell: vertexMesh(scene, `${name}_shell`, shellPositions, shellIndices),
    interior: vertexMesh(scene, `${name}_interior`, interiorPositions, interiorIndices),
  };
}

function tunnelStripIndices(count: number, steps: number, flip: boolean): number[] {
  const indices: number[] = [];
  for (let i = 0; i < steps; i++) {
    const a = i * count;
    const b = a + count;
    for (let j = 0; j < count - 1; j++) {
      if (flip) indices.push(a + j, a + j + 1, b + j, a + j + 1, b + j + 1, b + j);
      else indices.push(a + j, b + j, a + j + 1, a + j + 1, b + j, b + j + 1);
    }
  }
  return indices;
}

function vertexMesh(scene: Scene, name: string, positions: number[], indices: number[]): Mesh {
  const mesh = new MeshClass(name, scene);
  const data = new VertexData();
  data.positions = positions;
  data.indices = indices;
  const normals: number[] = [];
  VertexData.ComputeNormals(positions, indices, normals);
  data.normals = normals;
  data.applyToMesh(mesh);
  return mesh;
}

function tunnelSection(width: number): { x: number; y: number }[] {
  const gateWidth = width + 8;
  const wall = 3;
  const arch = 5;
  const half = gateWidth / 2;
  return [
    { x: -half, y: 0 },
    { x: -half, y: wall },
    ...Array.from({ length: 7 }, (_, i) => {
      const x = -half + (gateWidth * i) / 6;
      return { x, y: wall + arch * Math.sqrt(1 - (x / half) ** 2) };
    }),
    { x: half, y: wall },
    { x: half, y: 0 },
  ];
}

function tunnelPortals(
  scene: Scene,
  graph: RoadGraph,
  id: number,
  width: number,
  material: StandardMaterial,
  color: Color3,
): (Mesh | LinesMesh)[] {
  const seg = graph.segment(id);
  return [
    ...tunnelPortal(scene, graph, id, 0, width, 1, material, color),
    ...tunnelPortal(scene, graph, id, seg.length, width, -1, material, color),
  ];
}

function tunnelPortal(
  scene: Scene,
  graph: RoadGraph,
  id: number,
  distance: number,
  width: number,
  direction: 1 | -1,
  material: StandardMaterial,
  color: Color3,
): (Mesh | LinesMesh)[] {
  const { position, tangent } = graph.pointAt(id, distance);
  const y = terrainHeight(position.x, position.z) + MARK_LIFT;
  const exterior = portalExterior(scene, `tunnel_headwall_${id}_${distance}`, position, tangent, width, direction, y);
  for (const mesh of exterior) {
    mesh.material = material;
    mesh.isPickable = false;
  }

  const portal = portalMesh(scene, `tunnel_portal_${id}_${distance}`, position, tangent, width, direction, y);
  portal.material = material;
  portal.isPickable = false;

  const lip = portalOutline(position, tangent, width, y);
  return [...exterior, portal, styledLine(scene, `tunnel_lip_${id}_${distance}`, lip, color)];
}

function portalExterior(
  scene: Scene,
  name: string,
  center: { x: number; z: number },
  tangent: { x: number; z: number },
  width: number,
  direction: 1 | -1,
  y: number,
): Mesh[] {
  const gate = width + 8;
  const side = 5;
  const height = 9;
  const top = 3;
  const depth = 5;
  const rotation = Math.atan2(tangent.x * direction, tangent.z * direction);
  const n = perpXZ(normalizeXZ({ x: tangent.x, y: 0, z: tangent.z }));
  const block = (label: string, x: number, boxWidth: number, boxHeight: number, cy: number) => {
    const mesh = MeshBuilder.CreateBox(`${name}_${label}`, { width: boxWidth, height: boxHeight, depth }, scene);
    mesh.position.set(center.x + n.x * x, cy, center.z + n.z * x);
    mesh.rotation.y = rotation;
    return mesh;
  };
  return [
    block("left", -gate / 2 - side / 2, side, height, y + height / 2),
    block("right", gate / 2 + side / 2, side, height, y + height / 2),
    block("top", 0, gate + side * 2, top, y + height + top / 2),
  ];
}

function portalMesh(
  scene: Scene,
  name: string,
  center: { x: number; z: number },
  tangent: { x: number; z: number },
  width: number,
  direction: 1 | -1,
  y: number,
): Mesh {
  const t = normalizeXZ({ x: tangent.x * direction, y: 0, z: tangent.z * direction });
  const n = perpXZ(t);
  const inner = tunnelSection(width);
  const outer = tunnelSection(width + 8).map((p) => ({ x: p.x, y: p.y + 1.5 }));
  const positions: number[] = [];
  for (const d of [-1.4, 1.4]) {
    for (const section of [outer, inner]) {
      for (const p of section) positions.push(center.x + n.x * p.x + t.x * d, y + p.y, center.z + n.z * p.x + t.z * d);
    }
  }
  const indices: number[] = [];
  const count = inner.length;
  const frontOuter = 0;
  const frontInner = count;
  const backOuter = count * 2;
  const backInner = count * 3;
  for (let i = 0; i < count - 1; i++) {
    indices.push(frontOuter + i, frontOuter + i + 1, frontInner + i, frontOuter + i + 1, frontInner + i + 1, frontInner + i);
    indices.push(backOuter + i, backInner + i, backOuter + i + 1, backOuter + i + 1, backInner + i, backInner + i + 1);
    indices.push(frontOuter + i, backOuter + i, frontOuter + i + 1, frontOuter + i + 1, backOuter + i, backOuter + i + 1);
    indices.push(frontInner + i, frontInner + i + 1, backInner + i, frontInner + i + 1, backInner + i + 1, backInner + i);
  }
  const mesh = new MeshClass(name, scene);
  const data = new VertexData();
  data.positions = positions;
  data.indices = indices;
  const normals: number[] = [];
  VertexData.ComputeNormals(positions, indices, normals);
  data.normals = normals;
  data.applyToMesh(mesh);
  return mesh;
}

function portalOutline(center: { x: number; z: number }, tangent: { x: number; z: number }, width: number, y: number): Vector3[] {
  const n = perpXZ(normalizeXZ({ x: tangent.x, y: 0, z: tangent.z }));
  return tunnelSection(width).map((p) => new Vector3(center.x + n.x * p.x, y + p.y, center.z + n.z * p.x));
}

function roadStripMesh(scene: Scene, name: string, left: Vector3[], right: Vector3[]): Mesh {
  const positions: number[] = [];
  const indices: number[] = [];
  for (let i = 0; i < left.length; i++) positions.push(left[i]!.x, left[i]!.y, left[i]!.z, right[i]!.x, right[i]!.y, right[i]!.z);
  for (let i = 0; i < left.length - 1; i++) {
    const a = i * 2;
    indices.push(a, a + 1, a + 2, a + 1, a + 3, a + 2);
  }
  const mesh = new MeshClass(name, scene);
  const data = new VertexData();
  data.positions = positions;
  data.indices = indices;
  data.normals = Array.from({ length: positions.length / 3 }, () => [0, 1, 0]).flat();
  data.applyToMesh(mesh);
  return mesh;
}

/**
 * A triangle fan from the ring's centroid. The ring is convex, so a fan tessellates it
 * exactly -- no earcut, no dependency.
 */
function junctionMesh(scene: Scene, junction: JunctionGeometry): Mesh | null {
  const ring = junction.ring;
  if (ring.length < 3) return null;

  let cx = 0;
  let cy = 0;
  let cz = 0;
  for (const p of ring) {
    cx += p.x;
    cy += p.y;
    cz += p.z;
  }
  cx /= ring.length;
  cy /= ring.length;
  cz /= ring.length;

  const positions: number[] = [cx, cy + ROAD_LIFT, cz];
  for (const p of ring) positions.push(p.x, p.y + ROAD_LIFT, p.z);

  const indices: number[] = [];
  for (let i = 0; i < ring.length; i++) {
    indices.push(0, 1 + i, 1 + ((i + 1) % ring.length));
  }

  const mesh = new MeshClass(`junction_${junction.node}`, scene);
  const data = new VertexData();
  data.positions = positions;
  // Wound both ways, because the hull's winding can come out either way and a junction
  // culled from above is a hole. The normals are set explicitly rather than derived: a
  // horizontal polygon's normal is known, and deriving it from two windings cancels out.
  data.indices = [...indices, ...indices.slice().reverse()];
  data.normals = Array.from({ length: positions.length / 3 }, () => [0, 1, 0]).flat();
  data.applyToMesh(mesh);
  return mesh;
}
